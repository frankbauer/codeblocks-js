#!/usr/bin/env python3
"""Image provenance from image-credits.json: clean metadata and visible AI notices.

image-credits.json (repository root) has an entry for every image:

    "assets/robots/room.jpg": {"generator": "Generated", "name": "Krea 2", "overlay": true}

    generator  "Generated" (AI model), "Human" (hand made) or "Automated"
               (screenshots and files derived from existing content)
    name       the AI model or the author: "Krea 2", "T. Miehm", "F. Bauer"
    overlay    burn a visible "generated with <name>" notice into the image
               (only for generator "Generated")
    position   optional corner of the notice: "bottom-right" (default),
               "bottom-left", "top-right" or "top-left"
    scale      optional size factor of the notice (default 1; also scales its margin)
    offset     optional [x, y] shift of the notice in image pixels (+x right, +y down)
    source     IPTC digital source type (http://cv.iptc.org/newscodes/digitalsourcetype/),
               required for "Automated" (e.g. "screenCapture", "algorithmicMedia");
               defaults: Generated "trainedAlgorithmicMedia", Human "digitalCreation"

Paths matching a glob in "exclude" (e.g. vendored libraries) are ignored.

Commands (without paths, every manifest entry is processed):

    python3 tools/image_credits.py check            # images missing in the manifest, stale entries
    python3 tools/image_credits.py meta [paths]     # strip all metadata, write fresh EXIF and XMP
    python3 tools/image_credits.py overlay [paths]  # burn in the notice where overlay is true

`meta` rewrites the containers losslessly (PNG, JPEG, WebP; no re-encoding). It
removes EXIF, XMP, IPTC and text chunks and writes a minimal EXIF block plus an
XMP packet with the matching IPTC Photo Metadata (2025.1) properties:

    Generated   EXIF ImageDescription "Generated by <name>", Software <name>
                XMP  Iptc4xmpExt:DigitalSourceType, Iptc4xmpExt:AISystemUsed <name>,
                     dc:description
    Human       EXIF ImageDescription "Handmade by <name>", Artist, Copyright (c) <name>
                XMP  Iptc4xmpExt:DigitalSourceType, dc:creator, dc:rights,
                     xmpRights:Marked True, dc:description
    Automated   EXIF ImageDescription "Automatically derived from existing content",
                     Artist, Copyright (c) <name>
                XMP  as Human (without a name: DigitalSourceType and dc:description)

`overlay` renders the notice onto the unstamped original and records it, with its
parameters, in the EXIF ImageHistory tag ("Text overlay: generated with <name> (...)").
Files whose record matches the manifest are skipped, and `meta` keeps the record,
so both commands can be re-run safely; change scale/offset/position and re-run
`overlay` to re-render. Needs Pillow.

The originals are kept outside the repository (they carry no notice), in the folder
IMAGE_ORIGINALS_FOLDER from the environment or from .env in the repository root,
with the same relative paths as in the manifest. A still unstamped image without an
original there is copied into that folder before it is stamped.
"""

import argparse
import fnmatch
import io
import json
import math
import os
import shutil
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "image-credits.json"
EXTENSIONS = {".png", ".jpg", ".jpeg", ".webp", ".gif", ".avif", ".svg"}
WRITABLE = {".png", ".jpg", ".jpeg", ".webp"}
GENERATORS = {"Generated", "Human", "Automated"}
POSITIONS = {"bottom-right", "bottom-left", "top-right", "top-left"}
# IPTC digital source types (cv.iptc.org/newscodes/digitalsourcetype/, retired codes left out)
SOURCE_URI = "http://cv.iptc.org/newscodes/digitalsourcetype/"
SOURCE_TYPES = {
    "digitalCapture", "computationalCapture", "negativeFilm", "positiveFilm", "print", "humanEdits",
    "compositeWithTrainedAlgorithmicMedia", "algorithmicallyEnhanced", "digitalCreation", "dataDrivenMedia",
    "trainedAlgorithmicMedia", "algorithmicMedia", "screenCapture", "virtualRecording", "composite",
    "compositeCapture", "compositeSynthetic",
}
DEFAULT_SOURCE = {"Generated": "trainedAlgorithmicMedia", "Human": "digitalCreation"}

TAG_DESCRIPTION = 0x010E
TAG_SOFTWARE = 0x0131
TAG_ARTIST = 0x013B
TAG_COPYRIGHT = 0x8298
TAG_HISTORY = 0x9213  # ImageHistory: records the burned-in overlay
OVERLAY_PREFIX = "Text overlay: "

# "generated with" in a thin sans serif, the model name in a heavy serif (both SIL OFL, see fonts/)
FONT_DIR = Path(__file__).resolve().parent / "fonts"
FONT_REGULAR = FONT_DIR / "inter/Inter-Light.otf"
FONT_BOLD = FONT_DIR / "neuton/Neuton-ExtraBold.ttf"
FONT_SCALE = 0.034  # font size relative to sqrt(width * height)
BOLD_SCALE = 1.25  # Neuton has a small x-height: set it larger to match Inter
# distance of the text to the image edges (right/left edge to the ink, bottom edge to the
# baseline, top edge to the ink), in units of the font size. On the preview cards
# (object-fit: cover in a 2:3 box) ~16px are cropped off the bottom of the 576x896
# previews: 1 em (24px there) still keeps the descenders visible
MARGIN = 1.0


# --- manifest ---------------------------------------------------------------


def load_manifest(path: Path) -> dict:
    manifest = json.loads(path.read_text())
    for key, entry in manifest["images"].items():
        if entry.get("generator") not in GENERATORS:
            raise ValueError(f"{key}: generator must be one of {sorted(GENERATORS)}")
        if entry.get("overlay") and entry["generator"] != "Generated":
            raise ValueError(f"{key}: overlay is only allowed for generated images")
        if entry.get("position", "bottom-right") not in POSITIONS:
            raise ValueError(f"{key}: position must be one of {sorted(POSITIONS)}")
        if not isinstance(entry.get("scale", 1), (int, float)) or entry.get("scale", 1) <= 0:
            raise ValueError(f"{key}: scale must be a positive number")
        source = entry.get("source", DEFAULT_SOURCE.get(entry["generator"]))
        if source not in SOURCE_TYPES:
            raise ValueError(f"{key}: source must be an IPTC digital source type, e.g. screenCapture")
        offset = entry.get("offset", [0, 0])
        if not (isinstance(offset, list) and len(offset) == 2 and all(isinstance(v, (int, float)) for v in offset)):
            raise ValueError(f"{key}: offset must be [x, y]")
    return manifest


def originals_folder(root: Path):
    """IMAGE_ORIGINALS_FOLDER from the environment or from <root>/.env (relative to root)."""
    value = os.environ.get("IMAGE_ORIGINALS_FOLDER")
    env = root / ".env"
    if value is None and env.exists():
        for line in env.read_text().splitlines():
            k, sep, v = line.partition("=")
            if sep and k.strip() == "IMAGE_ORIGINALS_FOLDER":
                value = v.strip().strip("'\"")
    return (root / Path(value).expanduser()) if value else None


def overlay_record(entry: dict) -> str:
    """ImageHistory text for the notice, with every parameter that changes its rendering."""
    x, y = entry.get("offset", [0, 0])
    return (f"{OVERLAY_PREFIX}generated with {entry['name']} "
            f"({entry.get('position', 'bottom-right')}, scale {entry.get('scale', 1)}, offset {x},{y})")


def repo_images(root: Path, exclude) -> list:
    try:
        out = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True, check=True).stdout
        files = out.splitlines()
    except (OSError, subprocess.CalledProcessError):
        files = [p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()]
    return sorted(
        f for f in files
        if Path(f).suffix.lower() in EXTENSIONS and not any(fnmatch.fnmatch(f, g) for g in exclude)
    )


def selected(manifest: dict, root: Path, paths) -> list:
    """Manifest keys for the given paths (files or folders), all entries without paths."""
    images = manifest["images"]
    if not paths:
        return list(images)
    keys = []
    for p in paths:
        rel = Path(p).resolve().relative_to(root.resolve()).as_posix()
        hits = [k for k in images if k == rel or k.startswith(rel.rstrip("/") + "/")]
        if not hits:
            print(f"· {p}: not in the manifest", file=sys.stderr)
        keys += hits
    return keys


# --- EXIF and containers ----------------------------------------------------


def tags_for(entry: dict, history: str = "") -> dict:
    name, kind = entry.get("name", ""), entry["generator"]
    if kind == "Generated":
        tags = {TAG_DESCRIPTION: f"Generated by {name}", TAG_SOFTWARE: name}
    elif kind == "Human":
        tags = {TAG_DESCRIPTION: f"Handmade by {name}", TAG_ARTIST: name, TAG_COPYRIGHT: f"Copyright (c) {name}"}
    else:
        tags = {TAG_DESCRIPTION: "Automatically derived from existing content"}
        if name:
            tags |= {TAG_ARTIST: name, TAG_COPYRIGHT: f"Copyright (c) {name}"}
    tags[TAG_HISTORY] = history
    return tags


def xmp_for(entry: dict) -> bytes:
    """XMP packet with the IPTC provenance and copyright properties of a manifest entry."""
    from xml.sax.saxutils import escape, quoteattr
    name, kind = entry.get("name", ""), entry["generator"]
    source = entry.get("source", DEFAULT_SOURCE.get(kind))
    description = tags_for(entry)[TAG_DESCRIPTION]
    attrs = {"Iptc4xmpExt:DigitalSourceType": SOURCE_URI + source}
    props = [f'<dc:description><rdf:Alt><rdf:li xml:lang="x-default">{escape(description)}</rdf:li></rdf:Alt></dc:description>']
    if kind == "Generated":
        attrs["Iptc4xmpExt:AISystemUsed"] = name
    elif name:
        attrs["xmpRights:Marked"] = "True"
        props.insert(0, f"<dc:creator><rdf:Seq><rdf:li>{escape(name)}</rdf:li></rdf:Seq></dc:creator>")
        props.append(f'<dc:rights><rdf:Alt><rdf:li xml:lang="x-default">Copyright (c) {escape(name)}</rdf:li></rdf:Alt></dc:rights>')
    xml = (
        '<?xpacket begin="\ufeff" id="W5M0MpCehiHzreSzNTczkc9d"?>\n'
        '<x:xmpmeta xmlns:x="adobe:ns:meta/">'
        '<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
        '<rdf:Description rdf:about=""'
        ' xmlns:dc="http://purl.org/dc/elements/1.1/"'
        ' xmlns:xmpRights="http://ns.adobe.com/xap/1.0/rights/"'
        ' xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/"'
        + "".join(f" {k}={quoteattr(v)}" for k, v in attrs.items()) + ">"
        + "".join(props)
        + "</rdf:Description></rdf:RDF></x:xmpmeta>\n"
        '<?xpacket end="w"?>'
    )
    return xml.encode("utf-8")


def make_exif(tags: dict) -> bytes:
    """Minimal little-endian TIFF/EXIF block with the given ASCII tags (tag id -> text)."""
    entries = sorted((t, v) for t, v in tags.items() if v)
    ifd_offset = 8
    value_offset = ifd_offset + 2 + len(entries) * 12 + 4
    header = b"II*\0" + struct.pack("<I", ifd_offset)
    ifd = struct.pack("<H", len(entries))
    tail = b""
    for tag, value in entries:
        text = value.encode("utf-8") + b"\0"
        if len(text) <= 4:
            ifd += struct.pack("<HHI", tag, 2, len(text)) + text.ljust(4, b"\0")
        else:
            ifd += struct.pack("<HHII", tag, 2, len(text), value_offset + len(tail))
            tail += text + (b"\0" if len(text) & 1 else b"")
    ifd += struct.pack("<I", 0)  # no next IFD
    return header + ifd + tail


def read_history(data: bytes) -> str:
    """The overlay record (EXIF ImageHistory) of an encoded image, or ""."""
    try:
        from PIL import Image
        with Image.open(io.BytesIO(data)) as im:
            value = im.getexif().get(TAG_HISTORY) or ""
    except Exception:
        return ""
    return value.rstrip("\0") if value.startswith(OVERLAY_PREFIX) else ""


# WebP (RIFF chunks)
FLAG_EXIF, FLAG_XMP, FLAG_ALPHA = 0x08, 0x04, 0x10


def webp_chunks(data: bytes):
    chunks, pos = [], 12
    while pos + 8 <= len(data):
        fourcc = data[pos:pos + 4]
        size = struct.unpack("<I", data[pos + 4:pos + 8])[0]
        chunks.append((fourcc, data[pos + 8:pos + 8 + size]))
        pos += 8 + size + (size & 1)
    return chunks


def webp_chunk(fourcc: bytes, payload: bytes) -> bytes:
    return fourcc + struct.pack("<I", len(payload)) + payload + (b"\0" if len(payload) & 1 else b"")


def webp_canvas(fourcc: bytes, payload: bytes):
    """(width, height, has_alpha) of a simple-format WebP bitstream."""
    if fourcc == b"VP8 ":
        if payload[3:6] != b"\x9d\x01\x2a":
            raise ValueError("invalid VP8 frame header")
        w, h = struct.unpack("<HH", payload[6:10])
        return w & 0x3FFF, h & 0x3FFF, False
    if fourcc == b"VP8L":
        if payload[0] != 0x2F:
            raise ValueError("invalid VP8L signature")
        bits = struct.unpack("<I", payload[1:5])[0]
        return (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1, bool((bits >> 28) & 1)
    raise ValueError(f"unexpected image chunk {fourcc!r}")


def webp_rewrite(data: bytes, exif: bytes, xmp: bytes) -> bytes:
    kept = [(c, p) for c, p in webp_chunks(data) if c not in (b"EXIF", b"XMP ")]
    if kept[0][0] == b"VP8X":
        vp8x, body = bytearray(kept[0][1]), kept[1:]
    else:
        # simple format: wrap in an extended (VP8X) container so EXIF is allowed
        w, h, alpha = webp_canvas(*kept[0])
        vp8x = bytearray(10)
        vp8x[0] = FLAG_ALPHA if alpha else 0
        vp8x[4:7] = (w - 1).to_bytes(3, "little")
        vp8x[7:10] = (h - 1).to_bytes(3, "little")
        body = kept
    vp8x[0] |= FLAG_EXIF | FLAG_XMP
    out = webp_chunk(b"VP8X", bytes(vp8x))
    out += b"".join(webp_chunk(c, p) for c, p in body)
    out += webp_chunk(b"EXIF", exif) + webp_chunk(b"XMP ", xmp)
    return b"RIFF" + struct.pack("<I", len(out) + 4) + b"WEBP" + out


# PNG
PNG_SIG = b"\x89PNG\r\n\x1a\n"
PNG_DROP = {b"eXIf", b"tEXt", b"zTXt", b"iTXt", b"tIME"}


def png_chunk(kind: bytes, payload: bytes) -> bytes:
    import zlib
    return struct.pack(">I", len(payload)) + kind + payload + struct.pack(">I", zlib.crc32(kind + payload))


def png_rewrite(data: bytes, exif: bytes, xmp: bytes) -> bytes:
    out, pos, done = [PNG_SIG], 8, False
    # XMP in PNG: uncompressed iTXt chunk with the keyword "XML:com.adobe.xmp"
    itxt = b"XML:com.adobe.xmp\0" + b"\0\0" + b"\0" + b"\0" + xmp
    while pos < len(data):
        size = struct.unpack(">I", data[pos:pos + 4])[0]
        kind = data[pos + 4:pos + 8]
        if kind == b"IDAT" and not done:
            out.append(png_chunk(b"eXIf", exif) + png_chunk(b"iTXt", itxt))
            done = True
        if kind not in PNG_DROP:
            out.append(data[pos:pos + 12 + size])
        pos += 12 + size
    return b"".join(out)


# JPEG
JPEG_DROP = {0xE1, 0xED, 0xFE}  # APP1 (EXIF, XMP), APP13 (IPTC), COM


def jpeg_rewrite(data: bytes, exif: bytes, xmp: bytes) -> bytes:
    pos, head = 2, []
    while True:
        if data[pos] != 0xFF:
            raise ValueError("corrupt JPEG marker")
        marker = data[pos + 1]
        if marker == 0xFF:
            pos += 1
            continue
        if marker == 0xDA:  # start of scan: the rest is image data
            break
        size = struct.unpack(">H", data[pos + 2:pos + 4])[0]
        if marker not in JPEG_DROP:
            head.append((marker, data[pos:pos + 2 + size]))
        pos += 2 + size
    app1 = [b"Exif\0\0" + exif, b"http://ns.adobe.com/xap/1.0/\0" + xmp]
    app1 = [b"\xff\xe1" + struct.pack(">H", len(p) + 2) + p for p in app1]
    at = 1 if head and head[0][0] == 0xE0 else 0  # after JFIF APP0
    segments = [s for _, s in head]
    segments[at:at] = app1
    return b"\xff\xd8" + b"".join(segments) + data[pos:]


def write_meta(data: bytes, entry: dict, history: str = "") -> bytes:
    exif, xmp = make_exif(tags_for(entry, history)), xmp_for(entry)
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return webp_rewrite(data, exif, xmp)
    if data[:8] == PNG_SIG:
        return png_rewrite(data, exif, xmp)
    if data[:2] == b"\xff\xd8":
        return jpeg_rewrite(data, exif, xmp)
    raise ValueError("unsupported format (PNG, JPEG and WebP only)")


# --- overlay ----------------------------------------------------------------


def stamp(im, name: str, position="bottom-right", scale=1.0, offset=(0, 0)):
    """Burn "generated with <name>" (name in bold) into a corner of the image.

    Light text with a small drop shadow, or dark text without one on bright backgrounds.
    The text is rendered 4x supersampled as one layer, so both fonts share the exact
    (sub-pixel) baseline instead of being rounded to the pixel grid separately."""
    from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont, ImageStat
    im = im.convert("RGBA")
    w, h = im.size
    ss = 4
    size = max(8, math.sqrt(w * h) * FONT_SCALE * scale)
    regular = ImageFont.truetype(str(FONT_REGULAR), round(size * ss))
    bold = ImageFont.truetype(str(FONT_BOLD), round(size * BOLD_SCALE * ss))
    parts = [("generated with ", regular), (name, bold)]

    # ink bounds relative to the common baseline, in image pixels
    widths = [f.getlength(t) / ss for t, f in parts]
    top = min(f.getbbox(t, anchor="ls")[1] for t, f in parts) / ss
    bottom = max(f.getbbox(t, anchor="ls")[3] for t, f in parts) / ss
    vertical, horizontal = position.split("-")
    margin = size * MARGIN
    ink_left = parts[0][1].getbbox(parts[0][0], anchor="ls")[0] / ss
    ink_right = widths[0] + parts[1][1].getbbox(parts[1][0], anchor="ls")[2] / ss
    x = (margin - ink_left if horizontal == "left" else w - margin - ink_right) + offset[0]
    baseline = (margin - top if vertical == "top" else h - margin) + offset[1]

    # text mask on a padded local canvas, downsampled once
    pad = math.ceil(size * 0.3)
    x0, y0 = math.floor(x) - pad, math.floor(baseline + top) - pad
    cw, ch = math.ceil(sum(widths)) + 2 * pad + 1, math.ceil(bottom - top) + 2 * pad + 1
    big = Image.new("L", (cw * ss, ch * ss), 0)
    draw, cx = ImageDraw.Draw(big), (x - x0) * ss
    for (part, font), width in zip(parts, widths):
        draw.text((cx, (baseline - y0) * ss), part, font=font, fill=255, anchor="ls")
        cx += width * ss
    mask = big.resize((cw, ch), Image.LANCZOS)

    behind = Image.alpha_composite(Image.new("RGBA", im.size, (128, 128, 128, 255)), im)
    behind = behind.crop((x0, y0, x0 + cw, y0 + ch)).convert("L")
    bright = ImageStat.Stat(behind, mask).mean[0] > 150

    layer = Image.new("RGBA", (cw, ch), (0, 0, 0, 0))
    if bright:
        color = (28, 30, 40, 235)
    else:
        color = (255, 255, 255, 245)
        offset = max(1, round(size * 0.06))
        # crisp drop shadow plus a faint wide one that separates the text from busy backgrounds
        drop = ImageChops.offset(mask, offset, offset).filter(ImageFilter.GaussianBlur(size * 0.04))
        ambient = mask.filter(ImageFilter.GaussianBlur(size * 0.18))
        shadow_alpha = ImageChops.lighter(drop.point(lambda v: v * 200 // 255),
                                          ambient.point(lambda v: min(255, v * 2) * 120 // 255))
        layer = Image.composite(Image.new("RGBA", (cw, ch), (0, 0, 0, 255)), layer, shadow_alpha)
        layer.putalpha(shadow_alpha)
    text = Image.new("RGBA", (cw, ch), color[:3] + (0,))
    text.putalpha(mask.point(lambda v: v * color[3] // 255))
    layer = Image.alpha_composite(layer, text)
    im.alpha_composite(layer, dest=(x0, y0))
    return im


def encode(original, im, data: bytes) -> bytes:
    """Encode the stamped image in the format of the original."""
    buf = io.BytesIO()
    alpha = original.mode in ("RGBA", "LA", "PA") or "transparency" in original.info
    out = im if alpha else im.convert("RGB")
    fmt = original.format
    if fmt == "WEBP":
        lossless = any(c == b"VP8L" for c, _ in webp_chunks(data))
        out.save(buf, "WEBP", lossless=lossless, quality=90, method=6)
    elif fmt == "PNG":
        out.save(buf, "PNG", optimize=True)
    elif fmt == "JPEG":
        out.convert("RGB").save(buf, "JPEG", quality=92, icc_profile=original.info.get("icc_profile"))
    else:
        raise ValueError(f"cannot re-encode {fmt}")
    return buf.getvalue()


# --- commands ---------------------------------------------------------------


def cmd_check(manifest, root, _args):
    images = manifest["images"]
    present = repo_images(root, manifest.get("exclude", []))
    missing = [f for f in present if f not in images]
    stale = [k for k in images if not (root / k).exists()]
    for f in missing:
        print(f"missing  {f}")
    for k in stale:
        print(f"stale    {k}")
    originals = originals_folder(root)
    for k, e in images.items():
        if e.get("overlay") and not (originals and (originals / k).exists()):
            print(f"no original  {k}")
    counts = {}
    for e in images.values():
        key = (e["generator"], e.get("name", ""), bool(e.get("overlay")))
        counts[key] = counts.get(key, 0) + 1
    for (gen, name, overlay), n in sorted(counts.items()):
        print(f"{n:6}  {gen:<10} {name:<12} {'overlay' if overlay else ''}")
    return bool(missing or stale)


def cmd_meta(manifest, root, args):
    failed = False
    for key in selected(manifest, root, args.paths):
        path = root / key
        if path.suffix.lower() not in WRITABLE:
            print(f"· {key}: format not supported, skipped")
            continue
        try:
            data = path.read_bytes()
            result = write_meta(data, manifest["images"][key], read_history(data))
        except (OSError, ValueError) as e:
            print(f"{key}: {e}", file=sys.stderr)
            failed = True
            continue
        if result != data:
            path.write_bytes(result)
            print(f"✓ {key}")
    return failed


def cmd_overlay(manifest, root, args):
    from PIL import Image
    originals = originals_folder(root)
    if not originals:
        print("IMAGE_ORIGINALS_FOLDER is not set (environment or .env)", file=sys.stderr)
        return True
    failed = False
    for key in selected(manifest, root, args.paths):
        entry = manifest["images"][key]
        if not entry.get("overlay"):
            continue
        path, original_path = root / key, originals / key
        record = overlay_record(entry)
        try:
            current = path.read_bytes()
            if read_history(current) == record and not args.force:
                print(f"· {key}: up to date")
                continue
            if not original_path.exists():
                if read_history(current):
                    raise ValueError(f"stamped, but no original in {originals}")
                original_path.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(path, original_path)
                print(f"  archived original to {original_path}")
            data = original_path.read_bytes()
            with Image.open(io.BytesIO(data)) as original:
                stamped = stamp(original, entry["name"], entry.get("position", "bottom-right"),
                                entry.get("scale", 1), entry.get("offset", [0, 0]))
                encoded = encode(original, stamped, data)
            path.write_bytes(write_meta(encoded, entry, record))
            print(f"✓ {key}")
        except (OSError, ValueError) as e:
            print(f"{key}: {e}", file=sys.stderr)
            failed = True
    return failed


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--manifest", type=Path, default=MANIFEST)
