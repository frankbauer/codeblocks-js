    meta = sub.add_parser("meta", help="strip metadata and write EXIF from the manifest")
    meta.add_argument("paths", nargs="*", help="files or folders (default: all entries)")
    overlay = sub.add_parser("overlay", help="burn in the AI notice where overlay is true")
    overlay.add_argument("paths", nargs="*", help="files or folders (default: all entries)")
    overlay.add_argument("--force", action="store_true", help="re-render even if the record is up to date")
